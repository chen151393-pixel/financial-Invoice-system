"""发票行与子采购行的比对与分配：建议 → 人工通过 / 驳回 → 可取消。"""

from sqlalchemy import (
    CHAR,
    JSON,
    Boolean,
    CheckConstraint,
    Column,
    Computed,
    Index,
    Numeric,
    String,
    Table,
    UniqueConstraint,
    text,
)

from backend.core.schema import ID, TIMESTAMP, schema_metadata, table_options, timestamps

allocations = Table(
    "matching_allocations",
    schema_metadata,
    Column("id", ID, primary_key=True, autoincrement=True),
    Column("invoice_id", ID, nullable=False, comment="invoice_headers.id"),
    Column("invoice_item_id", ID, nullable=False, comment="invoice_items.id"),
    Column("purchase_line_id", ID, nullable=False, comment="source_purchase_order_lines.id"),
    Column("quantity", Numeric(26, 8), nullable=False),
    Column("amount", Numeric(24, 6), nullable=False, comment="分配的含税金额"),
    Column("status", String(24), nullable=False, server_default="proposed"),
    Column("confidence", Numeric(5, 2), comment="0-100；人工新建时为空"),
    Column("checks", JSON, comment="逐项比对：项目、发票值、采购值、结果、差额"),
    Column("exceeds_expected", Boolean, nullable=False, server_default=text("0")),
    Column(
        "closes_purchase_line",
        Boolean,
        nullable=False,
        server_default=text("0"),
        comment="人工确认该子采购行已开完（含差异）",
    ),
    Column("proposed_by", String(200), nullable=False, comment="system 或操作人"),
    Column("proposed_at", TIMESTAMP, nullable=False),
    Column("reviewed_by", String(200)),
    Column("reviewed_at", TIMESTAMP),
    Column("review_note", String(300), comment="有不一致项、超开或按差异结束时必填"),
    Column("cancelled_by", String(200)),
    Column("cancelled_at", TIMESTAMP),
    Column("cancel_reason", String(300)),
    Column("request_id", CHAR(36), nullable=False, comment="幂等"),
    Column(
        "active_invoice_item_id",
        ID,
        Computed("CASE WHEN status IN ('proposed','confirmed') THEN invoice_item_id END", persisted=True),
        comment="同一发票行与子采购行只有一条有效记录",
    ),
    *timestamps(),
    UniqueConstraint("request_id", name="uq_matching_request"),
    UniqueConstraint("active_invoice_item_id", "purchase_line_id", name="uq_matching_active_pair"),
    Index("ix_matching_purchase", "purchase_line_id", "status"),
    Index("ix_matching_invoice_item", "invoice_item_id", "status"),
    Index("ix_matching_queue", "status", "confidence"),
    CheckConstraint("status IN ('proposed','confirmed','rejected','cancelled')", name="ck_matching_status"),
    comment="发票行与子采购行的比对与分配",
    **table_options,
)
