"""发票行与子采购行的比对与分配：建议 → 人工通过 / 驳回 → 可取消。"""

from sqlalchemy import (
    CHAR,
    JSON,
    Boolean,
    CheckConstraint,
    Column,
    Computed,
    Index,
    Numeric,
    String,
    Table,
    UniqueConstraint,
    text,
)

from backend.core.schema import ID, TIMESTAMP, schema_metadata, table_options, timestamps

allocations = Table(
    "matching_allocations",
    schema_metadata,
    Column(
        "id", ID, comment="本地自增主键；与 NS 内部 ID、单号分开保存", primary_key=True, autoincrement=True
    ),
    Column("invoice_id", ID, nullable=False, comment="本地发票 ID，指向 invoice_headers.id"),
    Column(
        "invoice_item_id",
        ID,
        nullable=False,
        comment="发票逻辑商品行 ID，指向 invoice_items.id；版本变化不应借此重复占用额度",
    ),
    Column(
        "purchase_line_id",
        ID,
        nullable=False,
        comment="子采购明细 ID，指向 source_purchase_order_lines.id；开票业务围绕此身份组织",
    ),
    Column(
        "quantity",
        Numeric(26, 8),
        comment="发票口径的分配数量，用于占用发票行额度；与 purchase_quantity 分开",
        nullable=False,
    ),
    Column(
        "amount",
        Numeric(24, 6),
        nullable=False,
        comment="本次分配的含税金额；发票额度与采购收票均按此计量，不做跨币种换算",
    ),
    Column(
        "status",
        String(24),
        comment="分配状态：proposed 待审核建议；confirmed 已通过；rejected 已驳回；cancelled 已取消；有效性另看 verification_status",
        nullable=False,
        server_default="proposed",
    ),
    Column(
        "confidence",
        Numeric(5, 2),
        comment="建议置信度 0–100；高为 80 及以上，中为 50–79，低于 50 为低；人工新建可为空",
    ),
    Column("checks", JSON, comment="逐项比对结果 JSON，含发票值、采购值、结果、差额及相关校验上下文"),
    Column(
        "exceeds_expected",
        Boolean,
        comment="本次分配是否造成采购超开；不允许借此超过发票行本身的额度",
        nullable=False,
        server_default=text("0"),
    ),
    Column(
        "closes_purchase_line",
        Boolean,
        nullable=False,
        server_default=text("0"),
        comment="保留的旧差异结束标志；当前结束依据为 task_events + closure_event_id，不能凭此永久关闭后继任务",
    ),
    Column("proposed_by", String(200), nullable=False, comment="建议创建人：system 或认证操作者"),
    Column("proposed_at", TIMESTAMP, comment="建议创建时间，UTC", nullable=False),
    Column("reviewed_by", String(200), comment="通过或驳回该分配的操作者；后续复核另追加历史"),
    Column("reviewed_at", TIMESTAMP, comment="通过或驳回时间，UTC"),
    Column("review_note", String(300), comment="审核说明；不一致、超开等情形需要记录原因"),
    Column("cancelled_by", String(200), comment="取消分配的认证操作者"),
    Column("cancelled_at", TIMESTAMP, comment="取消分配时间，UTC"),
    Column("cancel_reason", String(300), comment="取消原因"),
    Column("request_id", CHAR(36), nullable=False, comment="幂等请求编号，防止同一操作重试时重复生成记录"),
    Column(
        "active_invoice_item_id",
        ID,
        Computed("CASE WHEN status IN ('proposed','confirmed') THEN invoice_item_id END", persisted=True),
        comment="自动生成：proposed 或 confirmed 取发票行 ID；配合 purchase_line_id 保证一对行最多一条有效记录",
    ),
    Column("invoice_version_id", ID, comment="分配原绑定的不可变发票版本，逻辑指向 invoice_versions.id"),
    Column("purchase_basis_id", ID, comment="全局子采购行开票依据版本 ID，逻辑指向 review_purchase_bases.id"),
    Column("purchase_quantity", Numeric(26, 8), comment="折算后的采购口径数量，任务按此累计收票"),
    Column("invoice_unit", String(50), comment="分配时发票数量的单位快照"),
    Column("purchase_unit", String(50), comment="分配时采购数量的单位快照"),
    Column("conversion_numerator", Numeric(28, 12), comment="换算分子；采购数量 = 发票数量 × 分子 ÷ 分母"),
    Column("conversion_denominator", Numeric(28, 12), comment="换算分母，业务校验要求大于 0"),
    Column(
        "conversion_evidence",
        JSON,
        comment="换算证据 JSON：reference 引用、invoiceVersionId、purchaseBasisId；不同单位必须有据换算",
    ),
    Column(
        "verification_status",
        String(24),
        comment="复核有效性：valid 有效；needs_review 待复核；invalid 已失效；与分配 status 独立",
        nullable=False,
        server_default="needs_review",
    ),
    Column("verification_issues", JSON, comment="待解决问题列表，如依据变化、发票换版或作废原因"),
    Column(
        "verification_history",
        JSON,
        comment="追加的失效、复核、依据承接历史；有效版本可由最新历史确定，原绑定版本保留",
    ),
    Column(
        "rule_version",
        String(40),
        comment="分配规则版本，当前为 ledger_v2",
        nullable=False,
        server_default="ledger_v2",
    ),
    *timestamps(),
    UniqueConstraint("request_id", name="uq_matching_request"),
    UniqueConstraint("active_invoice_item_id", "purchase_line_id", name="uq_matching_active_pair"),
    Index("ix_matching_purchase", "purchase_line_id", "status"),
    Index("ix_matching_invoice_item", "invoice_item_id", "status"),
    Index("ix_matching_queue", "status", "confidence"),
    CheckConstraint("status IN ('proposed','confirmed','rejected','cancelled')", name="ck_matching_status"),
    comment="发票行与子采购行的比对与分配",
    **table_options,
)
